1. Set up the Snowflake environment: this role has administrative privileges, so I can create warehouses, databases, roles, and grant permissions.

USE ROLE ACCOUNTADMIN;

--Create a virtual warehouse called DBT_WH - provides the computing resources needed to execute SQL queries.
-- XSMALL - because this is a small learning project.
-- AUTO_SUSPEND stops the warehouse after 60 seconds of inactivity to save credits
-- AUTO_RESUME starts it automatically when needed.

CREATE WAREHOUSE IF NOT EXISTS dbt_wh
WITH WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE;

-- Create a database called DBT_DB: contain my raw data and the transformed data generated by dbt

CREATE DATABASE IF NOT EXISTS dbt_db;

--Create a separate role called DBT_ROLE: allows us to control which resources dbt can access

CREATE ROLE IF NOT EXISTS dbt_role;

--2. Grant permissions: 
    -- allow DBT_ROLE to use the warehouse and access the database
    -- assign this role to my Snowflake user
    -- allows dbt to connect using the dedicated role instead of using the administrator account

GRANT USAGE ON WAREHOUSE dbt_wh TO ROLE dbt_role;
GRANT ALL ON DATABASE dbt_db TO ROLE dbt_role;
GRANT ROLE dbt_role TO USER "soloviova.kateryna";

-- 3. Verify the Snowflake setup: 

SELECT CURRENT_USER();
SHOW USERS;
SHOW WAREHOUSES;
SHOW DATABASES;
SHOW ROLES;

-- switch to DBT_ROLE and select the warehouse and database

USE ROLE DBT_ROLE;
USE WAREHOUSE DBT_WH;
USE DATABASE DBT_DB;
SELECT CURRENT_USER(), CURRENT_ROLE();

