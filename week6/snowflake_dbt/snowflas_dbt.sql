-- 5. Create schemas: this is where dbt creates my transformed models.

CREATE SCHEMA IF NOT EXISTS DBT_DB.DEV_KATERYNA;

--Inspect the database schemas and tables to understand which objects already exist

USE ROLE ACCOUNTADMIN;
USE DATABASE DBT_DB;

SHOW SCHEMAS IN DATABASE DBT_DB;
SHOW TABLES IN DATABASE DBT_DB;

-- This query uses Snowflake's INFORMATION_SCHEMA to list the tables in my database, excluding the system INFORMATION_SCHEMA.

SELECT TABLE_SCHEMA, TABLE_NAME
FROM DBT_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA NOT IN ('INFORMATION_SCHEMA')
ORDER BY TABLE_SCHEMA, TABLE_NAME;

-- 6. Create the raw data layer: this schema stores the original source tables before any transformations. I keep raw data separate from my development models.

USE ROLE ACCOUNTADMIN;
CREATE SCHEMA IF NOT EXISTS DBT_DB.RAW_DATA;

-- Inspect the imported CSV data to understand its structure, column names, and sample records before building dbt models.
SELECT *
FROM DBT_DB.RAW_DATA.ORDERS
LIMIT 10;

SELECT * FROM DBT_DB.RAW_DATA.CUSTOMERS;

-- 7. Grant dbt access to raw data: Initially, dbt could not access the RAW_DATA schema because DBT_ROLE did not have sufficient permissions.
-- fixed this by granting USAGE on the schema and SELECT on its tables. This allows dbt to read the original data.

GRANT USAGE ON SCHEMA DBT_DB.RAW_DATA TO ROLE DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DBT_DB.RAW_DATA TO ROLE DBT_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DBT_DB.RAW_DATA TO ROLE DBT_ROLE;

-- 8. Fix the customers table:
-- inspect the customer table structure.
--discovered that Snowflake had imported the CSV columns as C1, C2, C3, C4, and C5 instead of using the CSV header names

DESC TABLE DBT_DB.RAW_DATA.CUSTOMERS;

SELECT *
FROM DBT_DB.RAW_DATA.CUSTOMERS
LIMIT 10;

-- Recreate the customers table with meaningful column names and correct data types

CREATE OR REPLACE TABLE DBT_DB.RAW_DATA.CUSTOMERS AS
SELECT
    C1::NUMBER AS CUSTOMER_ID,
    C2::VARCHAR AS CUSTOMER_NAME,
    C3::VARCHAR AS EMAIL,
    C4::VARCHAR AS CITY,
    C5::DATE AS SIGNUP_DATE
FROM DBT_DB.RAW_DATA.CUSTOMERS
WHERE C1 <> 'customer_id';

-- Because I replaced the table, I grant SELECT permission again to DBT_ROLE so dbt can read the new table.
GRANT SELECT ON TABLE DBT_DB.RAW_DATA.CUSTOMERS TO ROLE DBT_ROLE;

