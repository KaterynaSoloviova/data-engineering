# Kafka + Snowflake Project
# Snowflake Database Setup, Authentication, Data Validation and Tableau Access

-- ============================================================
-- 1. CREATE DATABASE, SCHEMA AND TABLE
-- ============================================================

-- Create the main database for our e-commerce Kafka project.
-- IF NOT EXISTS prevents an error if the database already exists.
CREATE DATABASE IF NOT EXISTS KAFKA_DEMO;

-- Create a schema called REALTIME inside KAFKA_DEMO.
-- A schema is a logical container used to organize database objects.
CREATE SCHEMA IF NOT EXISTS KAFKA_DEMO.REALTIME;

-- Create the ORDERS table where our Kafka consumer will store
-- e-commerce order messages received from the Kafka topic.
CREATE TABLE IF NOT EXISTS KAFKA_DEMO.REALTIME.ORDERS (
    ORDER_ID INTEGER,              -- Unique identifier assigned to an order by the producer
    CUSTOMER_NAME VARCHAR(100),    -- Customer's full name
    CITY VARCHAR(50),              -- Customer's city
    PRODUCT VARCHAR(50),           -- Product purchased
    AMOUNT FLOAT,                  -- Order amount
    PAYMENT_MODE VARCHAR(20),      -- Payment method (UPI, Card or Cash)
    ORDER_TIME TIMESTAMP_NTZ       -- Date and time when the order was created
);

-- Inspect the table structure and verify that all columns
-- have been created with the expected data types.
DESCRIBE TABLE KAFKA_DEMO.REALTIME.ORDERS;


-- ============================================================
-- 2. INVESTIGATE SNOWFLAKE AUTHENTICATION
-- ============================================================

-- List security integrations configured in the Snowflake account.
-- We used this to investigate available authentication methods.
SHOW SECURITY INTEGRATIONS;

-- Inspect the Google OpenID Connect integration.
-- This helped us understand the Google SSO configuration.
DESC SECURITY INTEGRATION OIDC_GOOGLE;

-- Search for integrations with OAUTH in their names.
-- We used this while investigating Tableau OAuth authentication.
SHOW SECURITY INTEGRATIONS LIKE '%OAUTH%';

-- Check the currently active Snowflake role.
SELECT CURRENT_ROLE();

-- Switch to ACCOUNTADMIN to perform account-level
-- administrative and security configuration.
USE ROLE ACCOUNTADMIN;

-- Inspect account-level OAuth parameters.
-- This was part of troubleshooting authentication.
SHOW PARAMETERS LIKE 'OAUTH%' IN ACCOUNT;

-- Check the current Snowflake username.
SELECT CURRENT_USER();

-- Inspect the Snowflake user configuration.
-- DESC USER displays user properties, including whether
-- key-pair authentication is configured.
DESC USER "soloviova.kateryna";


-- ============================================================
-- 3. CONFIGURE THE SNOWFLAKE WAREHOUSE
-- ============================================================

-- List available virtual warehouses and inspect their states.
SHOW WAREHOUSES;

-- Select the existing warehouse used by our Python consumer
-- and Tableau connection.
-- AUTO_RESUME is enabled, so Snowflake can start it when needed.
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;


-- ============================================================
-- 4. VALIDATE DATA INSERTED BY THE KAFKA CONSUMER
-- ============================================================

-- Count all records stored in the ORDERS table.
-- We expected 17 orders generated by the Python producer.
SELECT
    COUNT(*) AS TOTAL_ORDERS
FROM KAFKA_DEMO.REALTIME.ORDERS;

-- Check whether order number 1 was inserted successfully.
-- This query was used to investigate a failed insert
-- during the first consumer execution.
SELECT *
FROM KAFKA_DEMO.REALTIME.ORDERS
WHERE ORDER_ID = 1;

-- Manually restore the first order because its original
-- insert failed when no active warehouse was selected.
INSERT INTO KAFKA_DEMO.REALTIME.ORDERS
(
    ORDER_ID,
    CUSTOMER_NAME,
    CITY,
    PRODUCT,
    AMOUNT,
    PAYMENT_MODE,
    ORDER_TIME
)
VALUES
(
    1,
    'Jacqueline Fisher',
    'Mumbai',
    'Laptop',
    10408.09,
    'Cash',
    '2026-11-24 16:08:57.445165'
);

-- Verify the final number of orders after restoring order 1.
-- Expected result: 17.
SELECT COUNT(*) AS TOTAL_ORDERS
FROM KAFKA_DEMO.REALTIME.ORDERS;


-- ============================================================
-- 5. CREATE A DEDICATED ROLE FOR TABLEAU
-- ============================================================

-- Create a separate role for Tableau.
-- We avoid using ACCOUNTADMIN for the Tableau connection
-- because privileged administrative roles are blocked
-- by the Tableau OAuth security integration.
CREATE ROLE IF NOT EXISTS TABLEAU_READ_ROLE;

-- Allow Tableau to use the Snowflake virtual warehouse
-- to execute queries.
GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH
TO ROLE TABLEAU_READ_ROLE;

-- Allow Tableau to access the KAFKA_DEMO database.
GRANT USAGE ON DATABASE KAFKA_DEMO
TO ROLE TABLEAU_READ_ROLE;

-- Allow Tableau to access the REALTIME schema.
GRANT USAGE ON SCHEMA KAFKA_DEMO.REALTIME
TO ROLE TABLEAU_READ_ROLE;

-- Grant SELECT permission on the ORDERS table.
-- Tableau can read and visualize the data but cannot
-- insert, update or delete records using this permission.
GRANT SELECT ON TABLE KAFKA_DEMO.REALTIME.ORDERS
TO ROLE TABLEAU_READ_ROLE;

-- Assign the dedicated Tableau role to our Snowflake user.
-- This allows the user to select TABLEAU_READ_ROLE
-- when connecting from Tableau Desktop.
GRANT ROLE TABLEAU_READ_ROLE
TO USER "soloviova.kateryna";


